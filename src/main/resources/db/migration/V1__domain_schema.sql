CREATE TABLE company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corp_code VARCHAR(8) NOT NULL UNIQUE CHECK (corp_code ~ '^[0-9]{8}$'),
    name VARCHAR(300) NOT NULL,
    stock_code VARCHAR(6) UNIQUE CHECK (stock_code IS NULL OR stock_code ~ '^[0-9]{6}$'),
    corporate_registration_number VARCHAR(13),
    business_registration_number VARCHAR(10),
    ceo VARCHAR(300),
    industry_code VARCHAR(10),
    established_date DATE,
    address VARCHAR(500),
    homepage VARCHAR(500),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Prefix search only; arbitrary substring search needs a measured pg_trgm strategy later.
CREATE INDEX idx_company_name_prefix ON company (lower(name) text_pattern_ops);

CREATE TABLE raw_ingestion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    endpoint VARCHAR(50) NOT NULL,
    request_key VARCHAR(100) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    payload JSONB NOT NULL,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(company_id, endpoint, request_key, payload_hash)
);
CREATE INDEX idx_raw_ingestion_company_time ON raw_ingestion(company_id, fetched_at DESC);

CREATE TABLE financial_fact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    fiscal_year INTEGER NOT NULL CHECK (fiscal_year BETWEEN 2015 AND 2100),
    report_type VARCHAR(20) NOT NULL CHECK (report_type IN ('Q1','HALF_YEAR','Q3','ANNUAL')),
    statement_type VARCHAR(3) NOT NULL CHECK (statement_type IN ('CFS','OFS')),
    statement_division VARCHAR(3) NOT NULL CHECK (statement_division IN ('BS','IS','CIS','CF','SCE')),
    account_key VARCHAR(64) NOT NULL,
    account_code VARCHAR(300),
    standard_account VARCHAR(30) NOT NULL,
    raw_account_name VARCHAR(500) NOT NULL,
    account_detail TEXT NOT NULL DEFAULT '',
    amount NUMERIC(38,2),
    cumulative_amount NUMERIC(38,2),
    currency VARCHAR(3) NOT NULL,
    receipt_number VARCHAR(14) NOT NULL CHECK (receipt_number ~ '^[0-9]{14}$'),
    source VARCHAR(30) NOT NULL DEFAULT 'OPENDART',
    raw_ingestion_id BIGINT NOT NULL REFERENCES raw_ingestion(id),
    UNIQUE(company_id, fiscal_year, report_type, statement_type, statement_division, account_key)
);

CREATE TABLE disclosure (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL REFERENCES company(id),
    receipt_number VARCHAR(14) NOT NULL UNIQUE CHECK (receipt_number ~ '^[0-9]{14}$'),
    title VARCHAR(500) NOT NULL,
    disclosure_type VARCHAR(30) NOT NULL,
    receipt_date DATE NOT NULL,
    report_code VARCHAR(5),
    original_url VARCHAR(500) NOT NULL
);
CREATE INDEX idx_disclosure_company_date ON disclosure(company_id, receipt_date DESC, id DESC);
