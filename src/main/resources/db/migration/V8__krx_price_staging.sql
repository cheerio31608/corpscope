-- Append-only raw response staging. Deliberately not approved model prices/calendar data.
CREATE TABLE krx_price_snapshot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint VARCHAR(30) NOT NULL CHECK (endpoint IN ('stk_bydd_trd','ksq_bydd_trd')),
    trading_date DATE NOT NULL,
    payload_sha256 VARCHAR(64) NOT NULL CHECK (payload_sha256 ~ '^[a-f0-9]{64}$'),
    payload_utf8 BYTEA NOT NULL,
    collected_at TIMESTAMPTZ NOT NULL,
    reported_row_count INTEGER NOT NULL CHECK (reported_row_count BETWEEN 0 AND 20000),
    -- KRX official FAQ 19/26, reviewed 2026-10-15: unadjusted historical price, KRW and shares.
    price_basis VARCHAR(20) NOT NULL DEFAULT 'UNADJUSTED' CHECK (price_basis='UNADJUSTED'),
    currency VARCHAR(3) NOT NULL DEFAULT 'KRW' CHECK (currency='KRW'),
    volume_unit VARCHAR(10) NOT NULL DEFAULT 'SHARES' CHECK (volume_unit='SHARES'),
    basis_evidence_profile VARCHAR(60) NOT NULL DEFAULT 'KRX_FAQ19_26_REVIEW_20261015'
        CHECK (basis_evidence_profile='KRX_FAQ19_26_REVIEW_20261015'),
    official_publication_at TIMESTAMPTZ CHECK (official_publication_at IS NULL),
    calendar_verified BOOLEAN NOT NULL DEFAULT FALSE CHECK (NOT calendar_verified),
    corporate_actions_verified BOOLEAN NOT NULL DEFAULT FALSE CHECK (NOT corporate_actions_verified),
    UNIQUE(endpoint,trading_date,payload_sha256)
);
CREATE TABLE krx_price_quote_staging (
    snapshot_id BIGINT NOT NULL REFERENCES krx_price_snapshot(id),
    stock_code VARCHAR(6) NOT NULL CHECK (stock_code ~ '^[A-Z0-9]{6}$'),
    stock_name VARCHAR(300) NOT NULL,
    market VARCHAR(16) NOT NULL,
    open_price NUMERIC(38,8) CHECK (open_price>=0),
    high_price NUMERIC(38,8) CHECK (high_price>=0),
    low_price NUMERIC(38,8) CHECK (low_price>=0),
    close_price NUMERIC(38,8) CHECK (close_price>=0),
    volume NUMERIC(38,0) CHECK (volume>=0),
    listed_shares NUMERIC(38,0) CHECK (listed_shares>=0),
    PRIMARY KEY(snapshot_id,stock_code)
);
