-- A reviewed quarterly source is separate from the latest OpenDART financial_fact snapshot.
-- BS is a point-in-time balance; IS has both the current three-month and year-to-date periods.
CREATE TABLE quarterly_report_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    fiscal_year INTEGER NOT NULL CHECK (fiscal_year BETWEEN 2015 AND 2100),
    report_type VARCHAR(20) NOT NULL CHECK (report_type IN ('Q1','HALF_YEAR','Q3')),
    statement_type VARCHAR(3) NOT NULL CHECK (statement_type IN ('CFS','OFS')),
    receipt_number VARCHAR(14) NOT NULL,
    main_entry VARCHAR(100) NOT NULL,
    document_encoding VARCHAR(20) NOT NULL,
    extraction_profile VARCHAR(100) NOT NULL,
    evidence JSONB NOT NULL,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(company_id,fiscal_year,report_type,statement_type,receipt_number),
    FOREIGN KEY(company_id,receipt_number) REFERENCES report_document(company_id,receipt_number)
);

CREATE TABLE quarterly_version_fact (
    version_id BIGINT NOT NULL REFERENCES quarterly_report_version(id),
    standard_account VARCHAR(30) NOT NULL CHECK (standard_account IN
      ('REVENUE','OPERATING_PROFIT','NET_INCOME','ASSETS','LIABILITIES','EQUITY')),
    raw_account_name VARCHAR(300) NOT NULL,
    statement_division VARCHAR(3) NOT NULL CHECK (statement_division IN ('BS','IS')),
    amount NUMERIC(38,2) NOT NULL,
    cumulative_amount NUMERIC(38,2),
    currency VARCHAR(3) NOT NULL CHECK (currency='KRW'),
    display_unit BIGINT NOT NULL CHECK (display_unit=1000000),
    PRIMARY KEY(version_id,standard_account),
    CHECK ((statement_division='BS' AND cumulative_amount IS NULL AND standard_account IN ('ASSETS','LIABILITIES','EQUITY'))
        OR (statement_division='IS' AND cumulative_amount IS NOT NULL AND standard_account IN ('REVENUE','OPERATING_PROFIT','NET_INCOME')))
);

-- A complete, bounded A003 search interval; one-day receipt verification alone is insufficient
-- to claim absence of corrections on subsequent dates.
CREATE TABLE quarterly_filing_coverage (
    company_id BIGINT NOT NULL REFERENCES company(id),
    checked_from DATE NOT NULL,
    checked_through DATE NOT NULL,
    total_pages INTEGER NOT NULL CHECK (total_pages BETWEEN 1 AND 100),
    total_count INTEGER NOT NULL CHECK (total_count >= 1),
    verified_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY(company_id,checked_from,checked_through),
    CHECK (checked_through >= checked_from)
);
